def _shade(hexcol, f):
    hexcol = hexcol.lstrip("#")
    r, g, b = (int(hexcol[i:i + 2], 16) for i in (0, 2, 4))
    if f >= 1:
        r, g, b = (int(c + (255 - c) * (f - 1)) for c in (r, g, b))
    else:
        r, g, b = (int(c * f) for c in (r, g, b))
    return "#%02x%02x%02x" % (r, g, b)


def render(key, primary=None, secondary=None, outline="#1d1d22"):
    """Şablonu 16×16 renk listesine çevirir: [[ '#rrggbb' | None ] * 16] * 16."""
    _name, _kind, art = T[key]
    p, s = DEFAULT_COLORS.get(key, ("#888888", "#555555"))
    p, s = primary or p, secondary or s
    pal = {"o": outline, "a": p, "l": _shade(p, 1.35), "d": _shade(p, 0.7), "b": s, "c": _shade(s, 0.7),
           "w": "#ffffff"}
    rows = [r for r in art.strip("\n").split("\n")]
    out = []
    for y in range(16):
        line = rows[y] if y < len(rows) else ""
        out.append([pal.get(line[x]) if x < len(line) else None for x in range(16)])
    return out


def for_kind(kind):
    return [(k, v[0]) for k, v in T.items() if v[1] == kind]
